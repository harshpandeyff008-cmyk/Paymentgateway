import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import Sidebar from '../components/Sidebar';
import Navbar from '../components/Navbar';
import { useAuth } from '../context/AuthContext';
import { useToast } from '../context/ToastContext';
import { db } from '../firebase/config';
import { 
  collection, 
  query, 
  onSnapshot, 
  doc, 
  setDoc, 
  deleteDoc,
  getDocs,
  where
} from 'firebase/firestore';
import { 
  KeyRound, 
  Loader, 
  Plus, 
  Trash2, 
  Copy, 
  CheckCircle, 
  AlertTriangle,
  Clock,
  ShieldCheck,
  ShieldAlert,
  Search,
  Check,
  Ticket,
  Mail,
  UserCheck,
  ChevronDown
} from 'lucide-react';

export default function LicenseKeys() {
  const { currentUser, userDoc } = useAuth();
  const { showToast } = useToast();
  const navigate = useNavigate();
  const [sidebarOpen, setSidebarOpen] = useState(false);

  // Enforce access control for normal admins
  useEffect(() => {
    if (userDoc) {
      const hasAccess = userDoc.role === 'superadmin' || userDoc.allowLicenseKeys === true;
      if (!hasAccess) {
        showToast("Access Denied: You do not have permission to manage license keys.", "error");
        navigate('/admin-dashboard');
      }
    }
  }, [userDoc, navigate]);

  const [keys, setKeys] = useState([]);
  const [mailboxes, setMailboxes] = useState([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [deletingKeyId, setDeletingKeyId] = useState(null);

  // Form & Filter State
  const [selectedMailboxId, setSelectedMailboxId] = useState('');
  const [searchQuery, setSearchQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState('All'); // All, active, redeemed
  const [priceFilter, setPriceFilter] = useState('all');
  const [copiedKey, setCopiedKey] = useState(null);
  const [isDropdownOpen, setIsDropdownOpen] = useState(false);
  const [dropdownSearch, setDropdownSearch] = useState('');
  const [dropdownPriceFilter, setDropdownPriceFilter] = useState('all');

  const isSuperAdmin = userDoc?.role === 'superadmin';

  // 1. Load active keys in real-time
  useEffect(() => {
    if (!currentUser || !userDoc) return;

    const q = query(collection(db, 'license_keys'));
    const unsubscribe = onSnapshot(q, (snapshot) => {
      const list = [];
      snapshot.forEach((docSnap) => {
        const data = docSnap.data();
        const keyItem = { id: docSnap.id, ...data };

        // Superadmin sees all keys; Admin sees ONLY keys generated by them (or matching their UID/email)
        if (isSuperAdmin || data.createdByUid === currentUser.uid || data.createdByEmail === currentUser.email) {
          list.push(keyItem);
        }
      });
      // Sort: active keys first, then newest first
      list.sort((a, b) => {
        if (a.status === 'active' && b.status !== 'active') return -1;
        if (a.status !== 'active' && b.status === 'active') return 1;
        return new Date(b.createdAt) - new Date(a.createdAt);
      });
      setKeys(list);
      setLoading(false);
    }, (error) => {
      console.error("Error subscribing to license keys:", error);
      setLoading(false);
    });

    return () => unsubscribe();
  }, [currentUser, userDoc, isSuperAdmin]);

  // 2. Load verified mailboxes based on Administrator Permissions
  const loadVerifiedMailboxes = async () => {
    try {
      const allVerifiedList = [];
      const assignedList = [];

      const currentUid = currentUser?.uid;
      const userGmails = userDoc?.selectedGmails || [];
      const userZohos = userDoc?.selectedZohos || [];
      const userImaps = userDoc?.selectedImaps || [];

      // Query Gmail
      const qGmail = query(collection(db, 'gmail_credentials'), where('gmail_verified_by_admin', '==', true));
      const snapGmail = await getDocs(qGmail);
      snapGmail.forEach((docSnap) => {
        const data = docSnap.data();
        const mailboxItem = {
          id: docSnap.id,
          email: data.gmail_email,
          type: 'gmail',
          label: `${data.gmail_email} (Gmail)`,
          game_id_name: data.game_id_name || null,
          price_inr: data.price_inr !== undefined ? data.price_inr : null
        };
        allVerifiedList.push(mailboxItem);

        const isAssigned = isSuperAdmin ||
          data.assignedAdminId === currentUid ||
          userGmails.includes(data.gmail_email) ||
          userGmails.includes(docSnap.id);

        if (isAssigned) {
          assignedList.push(mailboxItem);
        }
      });

      // Query Zoho
      const qZoho = query(collection(db, 'zoho_credentials'), where('zoho_verified_by_admin', '==', true));
      const snapZoho = await getDocs(qZoho);
      snapZoho.forEach((docSnap) => {
        const data = docSnap.data();
        const mailboxItem = {
          id: docSnap.id,
          email: data.zoho_email,
          type: 'zoho',
          label: `${data.zoho_email} (Zoho)`,
          game_id_name: data.game_id_name || null,
          price_inr: data.price_inr !== undefined ? data.price_inr : null
        };
        allVerifiedList.push(mailboxItem);

        const isAssigned = isSuperAdmin ||
          data.assignedAdminId === currentUid ||
          userZohos.includes(data.zoho_email) ||
          userZohos.includes(docSnap.id);

        if (isAssigned) {
          assignedList.push(mailboxItem);
        }
      });

      // Query IMAP
      const qImap = query(collection(db, 'imap_credentials'), where('imap_verified_by_admin', '==', true));
      const snapImap = await getDocs(qImap);
      snapImap.forEach((docSnap) => {
        const data = docSnap.data();
        const mailboxItem = {
          id: docSnap.id,
          email: data.imap_email,
          type: 'imap',
          label: `${data.imap_email} (Custom IMAP)`,
          game_id_name: data.game_id_name || null,
          price_inr: data.price_inr !== undefined ? data.price_inr : null
        };
        allVerifiedList.push(mailboxItem);

        const isAssigned = isSuperAdmin ||
          data.assignedAdminId === currentUid ||
          userImaps.includes(data.imap_email) ||
          userImaps.includes(docSnap.id);

        if (isAssigned) {
          assignedList.push(mailboxItem);
        }
      });

      // If user is superadmin or has specific mailboxes assigned, use assignedList.
      // If user has allowLicenseKeys but no specific mailboxes assigned, fallback to allVerifiedList so they aren't blocked!
      const finalList = assignedList.length > 0 ? assignedList : (userDoc?.allowLicenseKeys ? allVerifiedList : []);

      setMailboxes(finalList);
      if (finalList.length > 0) {
        setSelectedMailboxId(prev => (prev && finalList.some(m => m.id === prev)) ? prev : finalList[0].id);
      } else {
        setSelectedMailboxId('');
      }
    } catch (err) {
      console.error("Error loading verified mailboxes:", err);
      showToast("Failed to fetch verified mailboxes.", "error");
    }
  };

  useEffect(() => {
    if (currentUser && userDoc) {
      loadVerifiedMailboxes();
    }
  }, [currentUser, userDoc]);

  // 3. Generate License Key
  const handleGenerateKey = async (e) => {
    e.preventDefault();
    if (!selectedMailboxId) {
      showToast("Please select a target mailbox first.", "error");
      return;
    }

    const selectedMailbox = mailboxes.find(m => m.id === selectedMailboxId);
    if (!selectedMailbox) {
      showToast("Selected mailbox not found.", "error");
      return;
    }

    setGenerating(true);
    try {
      // Create random 16 mixed character key: XXXX-XXXX-XXXX-XXXX
      const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
      let p1 = '', p2 = '', p3 = '', p4 = '';
      for (let i = 0; i < 4; i++) {
        p1 += chars.charAt(Math.floor(Math.random() * chars.length));
        p2 += chars.charAt(Math.floor(Math.random() * chars.length));
        p3 += chars.charAt(Math.floor(Math.random() * chars.length));
        p4 += chars.charAt(Math.floor(Math.random() * chars.length));
      }
      const generatedKey = `${p1}-${p2}-${p3}-${p4}`;

      // Save key doc in Firestore with creator metadata
      await setDoc(doc(db, 'license_keys', generatedKey), {
        keyId: generatedKey,
        assignedMailbox: selectedMailbox.email,
        mailboxType: selectedMailbox.type,
        mailboxDocId: selectedMailbox.id,
        status: 'active',
        createdAt: new Date().toISOString(),
        createdByUid: currentUser.uid,
        createdByEmail: currentUser.email,
        createdByRole: userDoc?.role || 'admin',
        redeemedBy: null,
        redeemedAt: null
      });

      showToast(`Generated license key: ${generatedKey}`, "success");
    } catch (error) {
      console.error("Error saving license key:", error);
      showToast("Failed to generate license key.", "error");
    } finally {
      setGenerating(false);
    }
  };

  // 4. Delete/Revoke License Key
  const handleRevokeKey = async (keyDoc) => {
    // Rule: Normal Admin can only revoke keys they created. SuperAdmin can delete everything.
    const isOwner = keyDoc.createdByUid === currentUser.uid;
    if (!isSuperAdmin && !isOwner) {
      showToast("Access Denied: You can only delete keys that you generated.", "error");
      return;
    }

    if (!window.confirm("Are you sure you want to delete this license key? Users will no longer be able to use it to register.")) return;

    setDeletingKeyId(keyDoc.keyId);
    try {
      await deleteDoc(doc(db, 'license_keys', keyDoc.keyId));
      showToast("License key revoked successfully.", "success");
    } catch (error) {
      console.error("Error deleting key:", error);
      showToast("Failed to revoke key.", "error");
    } finally {
      setDeletingKeyId(null);
    }
  };

  // 5. Copy key helper
  const handleCopyKey = (keyId) => {
    navigator.clipboard.writeText(keyId);
    setCopiedKey(keyId);
    showToast("License key copied!", "success");
    setTimeout(() => setCopiedKey(null), 2000);
  };

  // 6. Metrics Calculations
  const totalKeys = keys.length;
  const activeKeys = keys.filter(k => k.status === 'active').length;
  const redeemedKeys = keys.filter(k => k.status === 'redeemed').length;

  // 7. Filtering logic
  const filteredKeys = keys.filter(keyDoc => {
    const matchMailbox = mailboxes.find(m => m.email === keyDoc.assignedMailbox);
    const gameIdStr = matchMailbox?.game_id_name || '';
    const priceStr = matchMailbox?.price_inr !== undefined && matchMailbox?.price_inr !== null ? String(matchMailbox.price_inr) : '';
    const priceVal = matchMailbox?.price_inr !== undefined && matchMailbox?.price_inr !== null ? Number(matchMailbox.price_inr) : null;

    if (priceFilter !== 'all') {
      if (priceVal !== Number(priceFilter)) {
        return false;
      }
    }

    const matchesSearch = 
      keyDoc.keyId.toLowerCase().includes(searchQuery.toLowerCase()) ||
      keyDoc.assignedMailbox.toLowerCase().includes(searchQuery.toLowerCase()) ||
      gameIdStr.toLowerCase().includes(searchQuery.toLowerCase()) ||
      priceStr.includes(searchQuery);
    
    if (statusFilter === 'All') return matchesSearch;
    if (statusFilter === 'Active') return matchesSearch && keyDoc.status === 'active';
    if (statusFilter === 'Redeemed') return matchesSearch && keyDoc.status === 'redeemed';
    return matchesSearch;
  });

  const selectedMailbox = mailboxes.find(m => m.id === selectedMailboxId);

  return (
    <div className="min-h-screen bg-gray-50 dark:bg-gray-950 flex font-sans select-none">
      <Sidebar isOpen={sidebarOpen} setIsOpen={setSidebarOpen} />

      <div className="flex-1 lg:pl-72 flex flex-col min-w-0 h-screen overflow-hidden">
        <Navbar onMenuClick={() => setSidebarOpen(true)} />

        <main className="flex-1 overflow-y-auto p-6 space-y-6">
          {/* Header */}
          <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
            <div>
              <h2 className="text-2xl font-black text-gray-900 dark:text-white tracking-tight flex items-center gap-2">
                <div className="w-10 h-10 rounded-xl bg-indigo-50 dark:bg-indigo-950/40 border border-indigo-100 dark:border-indigo-900/50 flex items-center justify-center text-indigo-600 dark:text-indigo-400 shadow-sm shrink-0">
                  <KeyRound className="w-5.5 h-5.5" />
                </div>
                <span>Registration License Keys</span>
              </h2>
              <p className="text-xs text-gray-455 dark:text-gray-500 font-semibold mt-1">
                Generate single-use license keys mapped to specific mailboxes to allow client self-signup.
              </p>
            </div>
          </div>

          {/* Quick Metrics Bar */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-6">
            <div className="bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 p-5 rounded-3xl shadow-sm flex items-center gap-4">
              <div className="w-11 h-11 rounded-2xl bg-indigo-50 dark:bg-indigo-950/30 text-indigo-650 dark:text-indigo-400 flex items-center justify-center border border-indigo-100 dark:border-indigo-900/40">
                <Ticket className="w-5 h-5" />
              </div>
              <div>
                <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest block">Total Generated</span>
                <span className="text-xl font-black text-gray-900 dark:text-white mt-0.5 block leading-none">{totalKeys}</span>
              </div>
            </div>

            <div className="bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 p-5 rounded-3xl shadow-sm flex items-center gap-4">
              <div className="w-11 h-11 rounded-2xl bg-emerald-50 dark:bg-emerald-950/30 text-emerald-650 dark:text-emerald-400 flex items-center justify-center border border-emerald-100 dark:border-emerald-900/40">
                <ShieldCheck className="w-5 h-5" />
              </div>
              <div>
                <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest block">Active / Unused</span>
                <span className="text-xl font-black text-gray-900 dark:text-white mt-0.5 block leading-none">{activeKeys}</span>
              </div>
            </div>

            <div className="bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 p-5 rounded-3xl shadow-sm flex items-center gap-4">
              <div className="w-11 h-11 rounded-2xl bg-rose-50 dark:bg-rose-955/20 text-rose-650 dark:text-rose-455 flex items-center justify-center border border-rose-100 dark:border-rose-950/20">
                <ShieldAlert className="w-5 h-5" />
              </div>
              <div>
                <span className="text-[10px] font-black text-gray-400 uppercase tracking-widest block">Redeemed / Claimed</span>
                <span className="text-xl font-black text-gray-900 dark:text-white mt-0.5 block leading-none">{redeemedKeys}</span>
              </div>
            </div>
          </div>

          {/* Generator Form */}
          <div className="bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 rounded-3xl p-6 shadow-sm">
            <h3 className="text-sm font-black text-gray-900 dark:text-white uppercase tracking-wider mb-4">
              Generate New License Key
            </h3>

            {mailboxes.length === 0 ? (
              <div className="p-4 bg-amber-50 dark:bg-amber-955/20 border border-amber-250 dark:border-amber-900/40 rounded-2xl flex items-center gap-3">
                <AlertTriangle className="w-5 h-5 text-amber-550 shrink-0" />
                <div className="text-xs font-bold text-amber-850 dark:text-amber-300">
                  {isSuperAdmin 
                    ? "No verified mailboxes available. Link Gmail/Zoho/IMAP mailboxes in profile settings first."
                    : "No mailboxes have been assigned to your admin account. Please contact a Super Admin."}
                </div>
              </div>
            ) : (
              <form onSubmit={handleGenerateKey} className="flex flex-col sm:flex-row items-end gap-4 max-w-2xl">
                <div className="relative flex-1 w-full z-30">
                  <label className="block text-xs font-bold text-gray-550 dark:text-gray-400 mb-1.5 uppercase font-black">
                    Select Target Garena Mailbox
                  </label>
                  
                  <button
                    type="button"
                    onClick={() => setIsDropdownOpen(!isDropdownOpen)}
                    className="w-full px-3.5 py-3 text-xs bg-gray-50 dark:bg-gray-800 border border-gray-205 dark:border-gray-700 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 text-gray-900 dark:text-white font-extrabold cursor-pointer flex items-center justify-between shadow-sm hover:bg-gray-100 dark:hover:bg-gray-750 transition-all"
                  >
                    <div className="flex items-center gap-2">
                      {selectedMailbox ? (
                        <>
                          <span className={`w-2 h-2 rounded-full shrink-0 ${
                            selectedMailbox.type === 'gmail' ? 'bg-rose-500 animate-pulse' : selectedMailbox.type === 'zoho' ? 'bg-amber-500' : 'bg-teal-500'
                          }`} />
                          <span>{selectedMailbox.label}</span>
                        </>
                      ) : (
                        <span className="text-gray-400 font-bold">Select Mailbox...</span>
                      )}
                    </div>
                    <ChevronDown className="w-4 h-4 text-gray-400 shrink-0" />
                  </button>

                  {isDropdownOpen && (
                    <>
                      {/* Overlay to catch clicks outside dropdown */}
                      <div 
                        className="fixed inset-0 z-40 cursor-default" 
                        onClick={() => setIsDropdownOpen(false)} 
                      />
                      
                      {/* Dropdown Options Container */}
                      <div className="absolute left-0 right-0 mt-2 bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 rounded-2xl shadow-xl z-50 p-2.5 space-y-2 animate-fade-in">
                        <div className="flex items-center gap-2">
                          <div className="relative flex-1">
                            <Search className="absolute left-2.5 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-gray-400" />
                            <input
                              type="text"
                              placeholder="Type to filter Garena mailboxes..."
                              value={dropdownSearch}
                              onChange={(e) => setDropdownSearch(e.target.value)}
                              className="w-full pl-8 pr-3 py-1.5 text-xs bg-gray-50 dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-lg focus:outline-none text-gray-900 dark:text-white placeholder-gray-400 dark:placeholder-gray-500 font-bold"
                              onClick={(e) => e.stopPropagation()} // Prevent closing on search input click
                            />
                          </div>

                          {/* Inline Dropdown Price Filter */}
                          <select
                            value={dropdownPriceFilter}
                            onChange={(e) => setDropdownPriceFilter(e.target.value)}
                            onClick={(e) => e.stopPropagation()} // Prevent dropdown close
                            className="px-2 py-1.5 text-[10px] font-black uppercase tracking-wider bg-gray-50 dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-lg text-gray-900 dark:text-white focus:outline-none cursor-pointer"
                          >
                            <option value="all" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">All Prices</option>
                            <option value="300" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹300</option>
                            <option value="500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹500</option>
                            <option value="1000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹1,000</option>
                            <option value="1500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹1,500</option>
                            <option value="2000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹2,000</option>
                            <option value="2500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹2,500</option>
                            <option value="3000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹3,000</option>
                            <option value="4000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹4,000</option>
                            <option value="5000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹5,000</option>
                            <option value="8000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹8,000</option>
                          </select>
                        </div>

                        <div className="space-y-0.5 max-h-52 overflow-y-auto pr-1">
                          {mailboxes.filter(m => {
                            if (dropdownPriceFilter !== 'all') {
                              const priceVal = m.price_inr !== undefined && m.price_inr !== null ? Number(m.price_inr) : null;
                              if (priceVal !== Number(dropdownPriceFilter)) return false;
                            }
                            const query = dropdownSearch.toLowerCase();
                            return m.label.toLowerCase().includes(query) ||
                                   (m.game_id_name || '').toLowerCase().includes(query) ||
                                   (m.price_inr !== undefined && m.price_inr !== null ? String(m.price_inr).includes(query) : false);
                          }).length === 0 ? (
                            <div className="p-2 text-center text-[10px] text-gray-400 font-bold">No mailboxes matched your query</div>
                          ) : (
                            mailboxes
                              .filter(m => {
                                if (dropdownPriceFilter !== 'all') {
                                  const priceVal = m.price_inr !== undefined && m.price_inr !== null ? Number(m.price_inr) : null;
                                  if (priceVal !== Number(dropdownPriceFilter)) return false;
                                }
                                const query = dropdownSearch.toLowerCase();
                                return m.label.toLowerCase().includes(query) ||
                                       (m.game_id_name || '').toLowerCase().includes(query) ||
                                       (m.price_inr !== undefined && m.price_inr !== null ? String(m.price_inr).includes(query) : false);
                              })
                              .map(m => {
                                const isChosen = m.id === selectedMailboxId;
                                return (
                                  <button
                                    key={m.id}
                                    type="button"
                                    onClick={() => {
                                      setSelectedMailboxId(m.id);
                                      setIsDropdownOpen(false);
                                      setDropdownSearch('');
                                      setDropdownPriceFilter('all');
                                    }}
                                    className={`w-full text-left px-3 py-2 rounded-lg text-xs font-bold transition-all flex items-center justify-between ${
                                      isChosen
                                        ? 'bg-indigo-600 text-white shadow-sm'
                                        : 'text-gray-700 dark:text-gray-300 hover:bg-gray-100 dark:hover:bg-gray-800'
                                    }`}
                                  >
                                    <div className="flex items-center gap-2 truncate pr-2">
                                      <span className={`w-1.5 h-1.5 rounded-full shrink-0 ${
                                        isChosen 
                                          ? 'bg-white' 
                                          : m.type === 'gmail' 
                                          ? 'bg-rose-500' 
                                          : m.type === 'zoho' 
                                          ? 'bg-amber-500' 
                                          : 'bg-teal-500'
                                      }`} />
                                      <span className="truncate">{m.email}</span>
                                      {m.game_id_name && (
                                        <span className={`px-1 rounded text-[8px] font-black uppercase tracking-wide shrink-0 border ${isChosen ? 'bg-white/30 text-white border-white/20' : 'bg-rose-50 dark:bg-rose-900/30 text-rose-600 dark:text-rose-400 border-rose-100 dark:border-rose-900/30'}`}>
                                          🎯 {m.game_id_name}
                                        </span>
                                      )}
                                      {m.price_inr !== undefined && m.price_inr !== null && (
                                        <span className={`px-1 rounded text-[8px] font-black uppercase tracking-wide shrink-0 border ${isChosen ? 'bg-white/30 text-white border-white/20' : 'bg-emerald-50 dark:bg-emerald-900/30 text-emerald-600 dark:text-emerald-400 border-emerald-100 dark:border-emerald-900/30'}`}>
                                          ₹{m.price_inr}
                                        </span>
                                      )}
                                    </div>
                                    <span className={`px-1.5 py-0.5 rounded text-[8px] font-black uppercase tracking-wide border shrink-0 ${
                                      isChosen
                                        ? 'bg-white/20 text-white border-white/30'
                                        : m.type === 'gmail'
                                        ? 'bg-rose-50 dark:bg-rose-900/30 text-rose-600 dark:text-rose-400 border-rose-200 dark:border-rose-900/40'
                                        : m.type === 'zoho'
                                        ? 'bg-amber-50 dark:bg-amber-900/30 text-amber-600 dark:text-amber-400 border-amber-200 dark:border-amber-900/40'
                                        : 'bg-teal-50 dark:bg-teal-900/30 text-teal-600 dark:text-teal-400 border-teal-200 dark:border-teal-900/40'
                                    }`}>
                                      {m.type}
                                    </span>
                                  </button>
                                );
                              })
                          )}
                        </div>
                      </div>
                    </>
                  )}
                </div>
                <button
                  type="submit"
                  disabled={generating}
                  className="w-full sm:w-auto shrink-0 flex items-center justify-center gap-1.5 px-6 py-3 bg-indigo-650 hover:bg-indigo-705 disabled:bg-indigo-400 text-white font-bold text-xs rounded-xl shadow-md shadow-indigo-600/10 transition-all"
                >
                  {generating ? (
                    <Loader className="w-4 h-4 animate-spin" />
                  ) : (
                    <Plus className="w-4 h-4" />
                  )}
                  <span>Generate Key</span>
                </button>
              </form>
            )}
          </div>

          {/* Search, Filter & Table Ledger */}
          <div className="bg-white dark:bg-gray-900 border border-gray-150 dark:border-gray-800 rounded-3xl shadow-sm overflow-hidden space-y-4">
            
            {/* Filter Bar */}
            <div className="p-4 border-b border-gray-100 dark:border-gray-800 flex flex-col sm:flex-row gap-4 items-center justify-between">
              <div className="flex flex-col sm:flex-row items-center gap-3 w-full sm:max-w-xl">
                <div className="relative w-full sm:w-64">
                  <Search className="absolute left-3.5 top-1/2 -translate-y-1/2 w-4 h-4 text-gray-400" />
                  <input
                    type="text"
                    placeholder="Search key ID or email..."
                    value={searchQuery}
                    onChange={(e) => setSearchQuery(e.target.value)}
                    className="w-full pl-10 pr-4 py-2.5 text-xs bg-gray-55 dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 text-gray-900 dark:text-white transition-all font-semibold"
                  />
                </div>

                {/* Price Filter Selector */}
                <div className="w-full sm:w-auto flex items-center gap-2 bg-gray-50 dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-xl px-3 py-2 shadow-sm">
                  <span className="text-[10px] font-black uppercase text-gray-400 whitespace-nowrap">Price:</span>
                  <select
                    value={priceFilter}
                    onChange={(e) => setPriceFilter(e.target.value)}
                    className="bg-transparent text-xs font-black text-gray-900 dark:text-white focus:outline-none cursor-pointer pr-4"
                  >
                    <option value="all" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">All Prices</option>
                    <option value="300" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹300</option>
                    <option value="500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹500</option>
                    <option value="1000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹1,000</option>
                    <option value="1500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹1,500</option>
                    <option value="2000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹2,000</option>
                    <option value="2500" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹2,500</option>
                    <option value="3000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹3,000</option>
                    <option value="4000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹4,000</option>
                    <option value="5000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹5,000</option>
                    <option value="8000" className="bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100">₹8,000</option>
                  </select>
                </div>
              </div>

              <div className="flex gap-2 w-full sm:w-auto shrink-0 justify-end">
                {['All', 'Active', 'Redeemed'].map(statusOpt => (
                  <button
                    key={statusOpt}
                    onClick={() => setStatusFilter(statusOpt)}
                    className={`px-3 py-1.5 rounded-lg text-xs font-bold transition-all ${
                      statusFilter === statusOpt
                        ? 'bg-indigo-600 text-white shadow-md shadow-indigo-650/15'
                        : 'bg-gray-100 dark:bg-gray-800 text-gray-500 dark:text-gray-400 hover:bg-gray-200 dark:hover:bg-gray-750'
                    }`}
                  >
                    {statusOpt}
                  </button>
                ))}
              </div>
            </div>

            {/* List */}
            {loading ? (
              <div className="p-12 flex flex-col items-center justify-center space-y-3">
                <Loader className="w-7 h-7 animate-spin text-indigo-655" />
                <span className="text-xs text-gray-455 font-bold">Synchronizing database log...</span>
              </div>
            ) : filteredKeys.length === 0 ? (
              <div className="p-12 text-center">
                <p className="text-xs text-gray-400 font-bold">No license keys match your parameters.</p>
              </div>
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-left border-collapse">
                  <thead>
                    <tr className="bg-gray-50/50 dark:bg-gray-855/20 border-b border-gray-100 dark:border-gray-855 text-[10px] font-black uppercase text-gray-400 tracking-wider">
                      <th className="px-6 py-3.5">License Key ID</th>
                      <th className="px-6 py-3.5">Linked Garena Mailbox</th>
                      <th className="px-6 py-3.5">Key Status</th>
                      <th className="px-6 py-3.5">Redemption Account</th>
                      <th className="px-6 py-3.5">Creator ID</th>
                      <th className="px-6 py-3.5 text-right">Actions</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-gray-100 dark:divide-gray-855/60 text-xs text-gray-750 dark:text-gray-300">
                    {filteredKeys.map((keyDoc) => {
                      const isRedeemed = keyDoc.status === 'redeemed';
                      const isOwner = keyDoc.createdByUid === currentUser.uid;
                      const canDelete = isSuperAdmin || isOwner;

                      return (
                        <tr key={keyDoc.id} className="hover:bg-gray-50/30 dark:hover:bg-gray-805/10">
                          {/* Key ID & Copy Option */}
                          <td className="px-6 py-4 font-mono font-black text-gray-900 dark:text-white flex items-center gap-2">
                            <span className="bg-gray-50 dark:bg-gray-800 px-2 py-1 rounded border border-gray-200/50 dark:border-gray-700/50">
                              {keyDoc.keyId}
                            </span>
                            <button
                              onClick={() => handleCopyKey(keyDoc.keyId)}
                              className="p-1 text-gray-400 hover:text-indigo-600 dark:hover:text-indigo-400 rounded-lg hover:bg-gray-100 dark:hover:bg-gray-800 transition-all"
                              title="Copy to Clipboard"
                            >
                              {copiedKey === keyDoc.keyId ? (
                                <Check className="w-3.5 h-3.5 text-emerald-600" />
                              ) : (
                                <Copy className="w-3.5 h-3.5" />
                              )}
                            </button>
                          </td>

                          {/* Linked Mailbox */}
                          <td className="px-6 py-4">
                            {(() => {
                              const matchMailbox = mailboxes.find(m => m.email === keyDoc.assignedMailbox);
                              return (
                                <>
                                  <div className="flex items-center gap-2 flex-wrap">
                                    <span className="font-semibold text-gray-900 dark:text-white leading-none">
                                      {keyDoc.assignedMailbox}
                                    </span>
                                    <span className={`px-1.5 py-0.5 rounded text-[8px] font-black uppercase tracking-wide border ${
                                      keyDoc.mailboxType === 'gmail' 
                                        ? 'bg-rose-50 dark:bg-rose-905/20 text-rose-600 border-rose-200 dark:border-rose-900/50' 
                                        : keyDoc.mailboxType === 'zoho'
                                        ? 'bg-amber-50 dark:bg-amber-905/20 text-amber-600 border-amber-200 dark:border-amber-900/50'
                                        : 'bg-teal-50 dark:bg-teal-905/20 text-teal-600 border-teal-200 dark:border-teal-900/50'
                                    }`}>
                                      {keyDoc.mailboxType}
                                    </span>
                                    {matchMailbox?.game_id_name && (
                                      <span className="px-1.5 py-0.5 bg-rose-50 dark:bg-rose-900/30 text-rose-600 dark:text-rose-400 text-[8px] font-black uppercase tracking-wide border border-rose-200 dark:border-rose-900/40 rounded shadow-sm">
                                        🎯 {matchMailbox.game_id_name}
                                      </span>
                                    )}
                                    {matchMailbox?.price_inr !== undefined && matchMailbox?.price_inr !== null && (
                                      <span className="px-1.5 py-0.5 bg-emerald-50 dark:bg-emerald-900/30 text-emerald-600 dark:text-emerald-400 text-[8px] font-black uppercase tracking-wide border border-emerald-200 dark:border-emerald-900/40 rounded shadow-sm">
                                        ₹{matchMailbox.price_inr}
                                      </span>
                                    )}
                                  </div>
                                  <span className="block text-[9px] text-gray-400 font-bold mt-1">
                                    Created: {new Date(keyDoc.createdAt).toLocaleString()}
                                  </span>
                                </>
                              );
                            })()}
                          </td>

                          {/* Status */}
                          <td className="px-6 py-4">
                            <span className={`inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[9px] font-black uppercase tracking-wider ${
                              isRedeemed 
                                ? 'bg-rose-50 dark:bg-rose-955/20 text-rose-600 border-rose-200' 
                                : 'bg-emerald-50 dark:bg-emerald-950/20 text-emerald-600 border-emerald-200'
                            }`}>
                              {isRedeemed ? (
                                <Clock className="w-2.5 h-2.5" />
                              ) : (
                                <ShieldCheck className="w-2.5 h-2.5" />
                              )}
                              <span>{keyDoc.status}</span>
                            </span>
                          </td>

                          {/* Redeemed By */}
                          <td className="px-6 py-4">
                            {isRedeemed ? (
                              <div className="space-y-0.5">
                                <div className="flex items-center gap-1 text-[10px] text-gray-500 font-bold font-mono">
                                  <UserCheck className="w-3.5 h-3.5 text-gray-400 shrink-0" />
                                  <span className="truncate max-w-[120px]">{keyDoc.redeemedBy}</span>
                                </div>
                                {keyDoc.redeemedAt && (
                                  <span className="block text-[9px] text-gray-400 font-bold">
                                    {new Date(keyDoc.redeemedAt).toLocaleString()}
                                  </span>
                                )}
                              </div>
                            ) : (
                              <span className="text-gray-400 dark:text-gray-600 font-medium italic">Unclaimed</span>
                            )}
                          </td>

                          {/* Creator Metadata */}
                          <td className="px-6 py-4">
                            <span className="font-semibold text-gray-900 dark:text-white">
                              {isOwner ? "You" : keyDoc.createdByEmail || "System"}
                            </span>
                            <span className="block text-[9px] text-gray-400 font-bold capitalize mt-0.5">
                              Role: {keyDoc.createdByRole}
                            </span>
                          </td>

                          {/* Revocation Controls */}
                          <td className="px-6 py-4 text-right">
                            <button
                              disabled={deletingKeyId === keyDoc.id || !canDelete}
                              onClick={() => handleRevokeKey(keyDoc)}
                              className={`p-2 rounded-xl transition-all ${
                                !canDelete 
                                  ? 'text-gray-300 dark:text-gray-700 cursor-not-allowed'
                                  : 'text-rose-600 hover:text-rose-700 hover:bg-rose-50 dark:hover:bg-rose-955/20'
                              }`}
                              title={canDelete ? "Revoke / Delete Key" : "Access Denied: Only key creator or Super Admin can delete"}
                            >
                              <Trash2 className="w-4 h-4" />
                            </button>
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </main>
      </div>
    </div>
  );
}
